function makeQuestions(topicId, items) {
  return items.map((item, index) => ({
    id: `${topicId}-${String(index + 1).padStart(2, "0")}`,
    prompt: item[0],
    answers: item[1],
    correct: item[2],
    explain: item[3],
    hint: item[4] || "先找题干中的限定词，再回到定义或要件判断。"
  }));
}

