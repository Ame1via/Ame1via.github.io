function subjectById(subjectId) {
  return subjects.find((subject) => subject.id === subjectId);
}

function addTopic(subjectId, topic) {
  subjectById(subjectId).topics.push(topic);
}

function addQuestionsToTopic(topicId, items) {
  const topic = subjects.flatMap((subject) => subject.topics).find((entry) => entry.id === topicId);
  topic.questions.push(...makeQuestions(`${topicId}-extra`, items));
}

